-- ===========================================================================
-- H2 本地文件数据库初始化脚本（考试机构考场与准考证建档工作区）
-- 启动时每次执行：建表用 IF NOT EXISTS，版本用 MERGE，已存在数据不受影响。
-- ===========================================================================

-- schema 版本登记（工作区版本选择可追溯）
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('exam-1', '考场与准考证建档：报名、编排、发证、查档四步');

-- 准考证号全局序列：只增不回退，回退批次也不复用号段，保证证号审计连续
CREATE SEQUENCE IF NOT EXISTS seq_admission_ticket_no START WITH 2026000001 INCREMENT BY 1;

-- ---------------------------------------------------------------------------
-- 建档：考点
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_exam_site (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_code       VARCHAR(32)  NOT NULL,
    site_name       VARCHAR(128) NOT NULL,
    location        VARCHAR(255) NOT NULL,                 -- 位置（地址/楼栋）
    contact_person  VARCHAR(64),
    contact_phone   VARCHAR(32),
    remark          VARCHAR(255),
    status          VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by       BIGINT,
    create_time     TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP,
    CONSTRAINT uk_exam_site_code UNIQUE (site_code)
);

-- ---------------------------------------------------------------------------
-- 建档：考场（归属于考点；容量、位置记全）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_exam_room (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id         BIGINT       NOT NULL,
    room_code       VARCHAR(32)  NOT NULL,                 -- 考点内考场号
    room_name       VARCHAR(128) NOT NULL,
    floor_no        VARCHAR(16),
    location        VARCHAR(255) NOT NULL,                 -- 位置（楼层/房间）
    capacity        INT          NOT NULL,                 -- 容量（座位数）
    status          VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_by       BIGINT,
    create_time     TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP,
    CONSTRAINT uk_exam_room_code UNIQUE (site_id, room_code),
    CONSTRAINT ck_exam_room_capacity CHECK (capacity > 0)
);

-- ---------------------------------------------------------------------------
-- 报名名册（考生建档）。勘误不抹旧值：本表只反映当前值，旧值进 t_roster_correction
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_examinee (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no            VARCHAR(32)  NOT NULL,             -- 报名导入批次
    line_no             INT,                                -- 批次内行号
    candidate_no        VARCHAR(64)  NOT NULL,             -- 报名号/身份证件号
    name                VARCHAR(64)  NOT NULL,
    gender              VARCHAR(8),
    id_type             VARCHAR(16)  NOT NULL DEFAULT 'ID_CARD',
    id_no               VARCHAR(32)  NOT NULL,
    phone               VARCHAR(32),
    school_or_org       VARCHAR(128),
    subject             VARCHAR(64),
    status              VARCHAR(16)  NOT NULL DEFAULT 'REGISTERED', -- REGISTERED/ASSIGNED
    create_by           BIGINT,
    create_time         TIMESTAMP,
    update_by           BIGINT,
    update_time         TIMESTAMP,
    CONSTRAINT uk_examinee_candidate UNIQUE (batch_no, candidate_no),
    CONSTRAINT uk_examinee_idno UNIQUE (id_type, id_no)
);
CREATE INDEX IF NOT EXISTS idx_examinee_name ON t_examinee (name);

-- ---------------------------------------------------------------------------
-- 名册勘误：保留旧值，标更正痕迹（不覆盖历史）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_roster_correction (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    examinee_id     BIGINT       NOT NULL,
    field_name      VARCHAR(32)  NOT NULL,
    old_value       VARCHAR(255),                           -- 旧值（保留，不抹）
    new_value       VARCHAR(255),
    reason          VARCHAR(255),
    corrected_by    BIGINT,
    corrected_name  VARCHAR(64),
    corrected_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_by       BIGINT,
    create_time     TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_correction_examinee ON t_roster_correction (examinee_id);

-- ---------------------------------------------------------------------------
-- 编排批次：阶段结果（预览/执行/回退）与最终结论分开
--   arrange_status: PREVIEWED / GENERATED / ROLLED_BACK
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_arrange_batch (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no            VARCHAR(32)  NOT NULL,
    subject             VARCHAR(64),
    total_count         INT          NOT NULL DEFAULT 0,   -- 影响范围：人数
    room_count          INT          NOT NULL DEFAULT 0,   -- 影响范围：考场数
    seat_strategy       VARCHAR(32)  NOT NULL DEFAULT 'SEQUENTIAL',
    ticket_no_prefix    VARCHAR(16),
    arrange_status      VARCHAR(16)  NOT NULL DEFAULT 'PREVIEWED',
    preview_snapshot    CLOB,                               -- 阶段结果：预览快照 JSON
    preview_by          BIGINT,
    preview_name        VARCHAR(64),
    preview_time        TIMESTAMP,
    generated_by        BIGINT,
    generated_name      VARCHAR(64),
    generated_time      TIMESTAMP,
    rollback_by         BIGINT,
    rollback_name       VARCHAR(64),
    rollback_time       TIMESTAMP,
    rollback_reason     VARCHAR(255),
    create_by           BIGINT,
    create_time         TIMESTAMP,
    update_by           BIGINT,
    update_time         TIMESTAMP,
    CONSTRAINT uk_arrange_batch_no UNIQUE (batch_no)
);

-- ---------------------------------------------------------------------------
-- 准考证：一人一条；证号全局唯一，撞号直接拒收
--   ticket_status: GENERATED / PRINTED / ISSUED
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_admission_ticket (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_no           VARCHAR(40)  NOT NULL,
    arrange_batch_id    BIGINT       NOT NULL,
    arrange_batch_no    VARCHAR(32)  NOT NULL,
    examinee_id         BIGINT       NOT NULL,
    candidate_no        VARCHAR(64)  NOT NULL,
    name                VARCHAR(64)  NOT NULL,
    id_type             VARCHAR(16),
    id_no               VARCHAR(32),
    subject             VARCHAR(64),
    site_id             BIGINT       NOT NULL,
    site_code           VARCHAR(32)  NOT NULL,
    site_name           VARCHAR(128) NOT NULL,
    site_location       VARCHAR(255),
    room_id             BIGINT       NOT NULL,
    room_code           VARCHAR(32)  NOT NULL,
    room_location       VARCHAR(255),
    seat_no             INT          NOT NULL,
    ticket_status       VARCHAR(16)  NOT NULL DEFAULT 'GENERATED',
    generated_by        BIGINT,
    generated_name      VARCHAR(64),
    generated_time      TIMESTAMP,
    printed_by          BIGINT,
    printed_name        VARCHAR(64),
    printed_time        TIMESTAMP,
    issued_by           BIGINT,
    issued_name         VARCHAR(64),
    issued_time         TIMESTAMP,
    create_by           BIGINT,
    create_time         TIMESTAMP,
    update_by           BIGINT,
    update_time         TIMESTAMP,
    CONSTRAINT uk_ticket_no UNIQUE (ticket_no),
    CONSTRAINT uk_ticket_examinee UNIQUE (examinee_id),
    CONSTRAINT uk_ticket_seat UNIQUE (room_id, seat_no),
    CONSTRAINT ck_ticket_seat CHECK (seat_no > 0)
);
CREATE INDEX IF NOT EXISTS idx_ticket_name ON t_admission_ticket (name);
CREATE INDEX IF NOT EXISTS idx_ticket_batch ON t_admission_ticket (arrange_batch_id);

-- ---------------------------------------------------------------------------
-- 发证流水：打证、发放两步都留经办和钟点；与准考证（最终结论）分表
--   action: PRINT / ISSUE
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_ticket_issue_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id       BIGINT       NOT NULL,
    ticket_no       VARCHAR(40)  NOT NULL,
    action          VARCHAR(16)  NOT NULL,
    from_status     VARCHAR(16),
    to_status       VARCHAR(16),
    operator_id     BIGINT,
    operator_name   VARCHAR(64)  NOT NULL,
    operate_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    remark          VARCHAR(255),
    create_by       BIGINT,
    create_time     TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_issue_log_ticket ON t_ticket_issue_log (ticket_id);

-- ---------------------------------------------------------------------------
-- 批次操作日志：编排批次的预览/生成/回退全程可追溯（状态回退留痕）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_batch_op_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT       NOT NULL,
    batch_no        VARCHAR(32)  NOT NULL,
    action          VARCHAR(24)  NOT NULL,                 -- PREVIEW/GENERATE/ROLLBACK
    detail          CLOB,
    operator_id     BIGINT,
    operator_name   VARCHAR(64)  NOT NULL,
    operate_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_by       BIGINT,
    create_time     TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_batch_op_log_batch ON t_batch_op_log (batch_id);
