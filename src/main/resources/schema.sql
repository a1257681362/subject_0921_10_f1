-- H2 本地文件数据库初始化脚本。
-- base-0：EVOPS 初始工作区
-- exam-1：考试机构考场与准考证建档工作区（报名 / 编排 / 发证 / 查档）

CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

-- ============ 考点 ============
CREATE TABLE IF NOT EXISTS t_exam_site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    address VARCHAR(255),
    contact_person VARCHAR(64),
    contact_phone VARCHAR(32),
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_exam_site_code UNIQUE (code)
);

-- ============ 考场（归属考点，容量、位置记全） ============
CREATE TABLE IF NOT EXISTS t_exam_room (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    room_no VARCHAR(32) NOT NULL,
    building VARCHAR(64),
    floor_no INT,
    capacity INT NOT NULL,
    location_desc VARCHAR(255),
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_exam_room_site_no UNIQUE (site_id, room_no),
    CONSTRAINT ck_exam_room_capacity CHECK (capacity > 0)
);

-- ============ 考试批次 ============
CREATE TABLE IF NOT EXISTS t_exam_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    site_id BIGINT NOT NULL,
    subject VARCHAR(128),
    exam_date DATE,
    start_time TIME,
    end_time TIME,
    -- CREATED 建档 / ARRANGED 已编排 / FINALIZED 已办结
    status VARCHAR(16) NOT NULL DEFAULT 'CREATED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_exam_batch_code UNIQUE (code)
);

-- ============ 报名名册 ============
CREATE TABLE IF NOT EXISTS t_registration (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    id_type VARCHAR(16) NOT NULL DEFAULT 'ID_CARD',
    id_no VARCHAR(32),
    gender VARCHAR(8),
    phone VARCHAR(32),
    batch_id BIGINT NOT NULL,
    subject VARCHAR(128),
    -- REGISTERED 已报名 / ARRANGED 已编排
    status VARCHAR(16) NOT NULL DEFAULT 'REGISTERED',
    correction_count INT NOT NULL DEFAULT 0,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_registration_reg_no UNIQUE (reg_no)
);
CREATE INDEX IF NOT EXISTS idx_registration_name ON t_registration (name);
CREATE INDEX IF NOT EXISTS idx_registration_batch ON t_registration (batch_id);

-- ============ 名册勘误（只追加，旧值留痕，不覆盖历史） ============
CREATE TABLE IF NOT EXISTS t_registration_correction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL,
    field_name VARCHAR(32) NOT NULL,
    field_label VARCHAR(64),
    old_value VARCHAR(255),
    new_value VARCHAR(255),
    reason VARCHAR(255),
    operator VARCHAR(64),
    corrected_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_correction_reg ON t_registration_correction (registration_id);

-- ============ 准考证（证号全局唯一；批次内考场+座位唯一） ============
CREATE TABLE IF NOT EXISTS t_admission_ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_no VARCHAR(40) NOT NULL,
    registration_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    seat_no INT NOT NULL,
    -- PENDING 待打印 / PRINTED 已打印 / ISSUED 已发放
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    printed_by VARCHAR(64),
    printed_at TIMESTAMP,
    issued_by VARCHAR(64),
    issued_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_ticket_no UNIQUE (ticket_no),
    CONSTRAINT uk_ticket_registration UNIQUE (registration_id),
    CONSTRAINT uk_ticket_seat UNIQUE (batch_id, room_id, seat_no),
    CONSTRAINT ck_ticket_seat CHECK (seat_no > 0)
);
CREATE INDEX IF NOT EXISTS idx_ticket_batch ON t_admission_ticket (batch_id);

-- ============ 阶段结果（与最终结论分表保存） ============
CREATE TABLE IF NOT EXISTS t_stage_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    -- IMPORT 报名导入 / ARRANGEMENT 编排 / PRINTING 打印 / ISSUANCE 发放
    stage VARCHAR(16) NOT NULL,
    affected_count INT NOT NULL DEFAULT 0,
    detail CLOB,
    operator VARCHAR(64),
    executed_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_stage_batch ON t_stage_result (batch_id);

-- ============ 最终结论 ============
CREATE TABLE IF NOT EXISTS t_final_conclusion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    conclusion_code VARCHAR(32) NOT NULL,
    summary VARCHAR(512),
    total_count INT NOT NULL DEFAULT 0,
    printed_count INT NOT NULL DEFAULT 0,
    issued_count INT NOT NULL DEFAULT 0,
    operator VARCHAR(64),
    concluded_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_final_conclusion_batch UNIQUE (batch_id)
);

-- ============ 工作区版本（版本选择 / 状态回退可追溯） ============
CREATE TABLE IF NOT EXISTS t_workspace_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(40) NOT NULL,
    label VARCHAR(128) NOT NULL,
    -- SNAPSHOT 快照 / ROLLBACK 回退生成
    kind VARCHAR(16) NOT NULL DEFAULT 'SNAPSHOT',
    restored_from_version VARCHAR(40),
    -- 同一时刻只有一个当前版本
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    snapshot CLOB,
    remark VARCHAR(255),
    operator VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_workspace_version_no UNIQUE (version_no)
);

-- 工作区版本事件（CREATE/SELECT/ROLLBACK 全程留痕；回退不清此表）
CREATE TABLE IF NOT EXISTS t_workspace_version_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    version_no VARCHAR(40) NOT NULL,
    action VARCHAR(16) NOT NULL,
    detail VARCHAR(512),
    operator VARCHAR(64),
    event_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_version_event_version ON t_workspace_version_event (version_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('exam-1', '考试机构考场与准考证建档工作区：报名、编排、发证、查档');
