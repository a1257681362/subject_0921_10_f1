package com.evops.exam.mapper;

import com.evops.exam.entity.AdmissionTicket;
import com.evops.exam.entity.ExamBatch;
import com.evops.exam.entity.ExamRoom;
import com.evops.exam.entity.ExamSite;
import com.evops.exam.entity.FinalConclusion;
import com.evops.exam.entity.Registration;
import com.evops.exam.entity.RegistrationCorrection;
import com.evops.exam.entity.StageResult;
import org.apache.ibatis.annotations.Delete;
import org.apache.ibatis.annotations.Insert;
import org.apache.ibatis.annotations.Mapper;
import org.apache.ibatis.annotations.Param;
import org.apache.ibatis.annotations.Select;
import org.apache.ibatis.annotations.Update;

/**
 * 版本回退专用：显式带主键的原样写回。
 * 业务外键（如准考证.registration_id）依赖快照中的原始 id，
 * H2 的 GENERATED BY DEFAULT 允许指定 id 插入。
 */
@Mapper
public interface RestoreMapper {

    @Delete("DELETE FROM t_final_conclusion")
    void clearConclusions();

    @Delete("DELETE FROM t_stage_result")
    void clearStageResults();

    @Delete("DELETE FROM t_admission_ticket")
    void clearTickets();

    @Delete("DELETE FROM t_registration_correction")
    void clearCorrections();

    @Delete("DELETE FROM t_registration")
    void clearRegistrations();

    @Delete("DELETE FROM t_exam_batch")
    void clearBatches();

    @Delete("DELETE FROM t_exam_room")
    void clearRooms();

    @Delete("DELETE FROM t_exam_site")
    void clearSites();

    @Insert("INSERT INTO t_exam_site (id, code, name, address, contact_person, contact_phone, status, remark, "
            + "create_by, create_time, update_by, update_time) VALUES "
            + "(#{id},#{code},#{name},#{address},#{contactPerson},#{contactPhone},#{status},#{remark},"
            + "#{createBy},#{createTime},#{updateBy},#{updateTime})")
    void insertSite(ExamSite s);

    @Insert("INSERT INTO t_exam_room (id, site_id, room_no, building, floor_no, capacity, location_desc, status, "
            + "create_by, create_time, update_by, update_time) VALUES "
            + "(#{id},#{siteId},#{roomNo},#{building},#{floorNo},#{capacity},#{locationDesc},#{status},"
            + "#{createBy},#{createTime},#{updateBy},#{updateTime})")
    void insertRoom(ExamRoom r);

    @Insert("INSERT INTO t_exam_batch (id, code, name, site_id, subject, exam_date, start_time, end_time, status, "
            + "remark, create_by, create_time, update_by, update_time) VALUES "
            + "(#{id},#{code},#{name},#{siteId},#{subject},#{examDate},#{startTime},#{endTime},#{status},"
            + "#{remark},#{createBy},#{createTime},#{updateBy},#{updateTime})")
    void insertBatch(ExamBatch b);

    @Insert("INSERT INTO t_registration (id, reg_no, name, id_type, id_no, gender, phone, batch_id, subject, "
            + "status, correction_count, remark, create_by, create_time, update_by, update_time) VALUES "
            + "(#{id},#{regNo},#{name},#{idType},#{idNo},#{gender},#{phone},#{batchId},#{subject},"
            + "#{status},#{correctionCount},#{remark},#{createBy},#{createTime},#{updateBy},#{updateTime})")
    void insertRegistration(Registration r);

    @Insert("INSERT INTO t_registration_correction (id, registration_id, field_name, field_label, old_value, "
            + "new_value, reason, operator, corrected_at, create_by, create_time, update_by, update_time) VALUES "
            + "(#{id},#{registrationId},#{fieldName},#{fieldLabel},#{oldValue},#{newValue},#{reason},#{operator},"
            + "#{correctedAt},#{createBy},#{createTime},#{updateBy},#{updateTime})")
    void insertCorrection(RegistrationCorrection c);

    @Insert("INSERT INTO t_admission_ticket (id, ticket_no, registration_id, batch_id, site_id, room_id, seat_no, "
            + "status, printed_by, printed_at, issued_by, issued_at, create_by, create_time, update_by, update_time) "
            + "VALUES (#{id},#{ticketNo},#{registrationId},#{batchId},#{siteId},#{roomId},#{seatNo},#{status},"
            + "#{printedBy},#{printedAt},#{issuedBy},#{issuedAt},"
            + "#{createBy},#{createTime},#{updateBy},#{updateTime})")
    void insertTicket(AdmissionTicket t);

    @Insert("INSERT INTO t_stage_result (id, batch_id, stage, affected_count, detail, operator, executed_at, "
            + "create_by, create_time, update_by, update_time) VALUES "
            + "(#{id},#{batchId},#{stage},#{affectedCount},#{detail},#{operator},#{executedAt},"
            + "#{createBy},#{createTime},#{updateBy},#{updateTime})")
    void insertStageResult(StageResult sr);

    @Insert("INSERT INTO t_final_conclusion (id, batch_id, conclusion_code, summary, total_count, printed_count, "
            + "issued_count, operator, concluded_at, create_by, create_time, update_by, update_time) VALUES "
            + "(#{id},#{batchId},#{conclusionCode},#{summary},#{totalCount},#{printedCount},#{issuedCount},"
            + "#{operator},#{concludedAt},#{createBy},#{createTime},#{updateBy},#{updateTime})")
    void insertConclusion(FinalConclusion fc);

    // 显式插 id 后必须把 IDENTITY 序列推到最大 id 之上，否则后续新增会主键冲突
    @Select("SELECT COALESCE(MAX(id),0) FROM t_exam_site")
    long maxSiteId();

    @Select("SELECT COALESCE(MAX(id),0) FROM t_exam_room")
    long maxRoomId();

    @Select("SELECT COALESCE(MAX(id),0) FROM t_exam_batch")
    long maxBatchId();

    @Select("SELECT COALESCE(MAX(id),0) FROM t_registration")
    long maxRegistrationId();

    @Select("SELECT COALESCE(MAX(id),0) FROM t_registration_correction")
    long maxCorrectionId();

    @Select("SELECT COALESCE(MAX(id),0) FROM t_admission_ticket")
    long maxTicketId();

    @Select("SELECT COALESCE(MAX(id),0) FROM t_stage_result")
    long maxStageResultId();

    @Select("SELECT COALESCE(MAX(id),0) FROM t_final_conclusion")
    long maxConclusionId();

    @Update("ALTER TABLE t_exam_site ALTER COLUMN id RESTART WITH ${value}")
    void restartSite(@Param("value") long value);

    @Update("ALTER TABLE t_exam_room ALTER COLUMN id RESTART WITH ${value}")
    void restartRoom(@Param("value") long value);

    @Update("ALTER TABLE t_exam_batch ALTER COLUMN id RESTART WITH ${value}")
    void restartBatch(@Param("value") long value);

    @Update("ALTER TABLE t_registration ALTER COLUMN id RESTART WITH ${value}")
    void restartRegistration(@Param("value") long value);

    @Update("ALTER TABLE t_registration_correction ALTER COLUMN id RESTART WITH ${value}")
    void restartCorrection(@Param("value") long value);

    @Update("ALTER TABLE t_admission_ticket ALTER COLUMN id RESTART WITH ${value}")
    void restartTicket(@Param("value") long value);

    @Update("ALTER TABLE t_stage_result ALTER COLUMN id RESTART WITH ${value}")
    void restartStageResult(@Param("value") long value);

    @Update("ALTER TABLE t_final_conclusion ALTER COLUMN id RESTART WITH ${value}")
    void restartConclusion(@Param("value") long value);
}
